import pathlib
import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(args=["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"])
        ctx=await b.new_context(viewport={"width":844,"height":390},device_scale_factor=1,is_mobile=True,has_touch=True)
        # i Chromium recenti chiedono il permesso dei sensori come Safari: nel test si concede subito
        await ctx.add_init_script("for(const E of [window.DeviceOrientationEvent,window.DeviceMotionEvent])if(E)E.requestPermission=()=>Promise.resolve('granted');")
        pg=await ctx.new_page();errs=[];pg.on("pageerror",lambda e:errs.append(str(e)))
        await pg.goto((pathlib.Path(__file__).resolve().parent.parent/"dist"/"test.html").as_uri());await pg.wait_for_timeout(1500)
        await pg.evaluate("__t.selectMap('acciaieria')");await pg.wait_for_timeout(500)
        print('touch on?',await pg.evaluate("document.body.classList.contains('touch')"),await pg.evaluate("!document.getElementById('touchwarn').hidden"))
        await pg.screenshot(path=str(pathlib.Path(__file__).resolve().parent)+"/t_menu.png")
        await pg.evaluate("document.getElementById('start').scrollIntoView()");await pg.tap("#start");await pg.wait_for_timeout(2500)
        print('state',await pg.evaluate("[__t.state,!document.getElementById('touch').hidden]"))
        cdp=await ctx.new_cdp_session(pg)
        async def T(typ,pts):await cdp.send("Input.dispatchTouchEvent",{"type":typ,"touchPoints":[{"x":x,"y":y,"id":i} for i,(x,y) in pts]})
        p0=await pg.evaluate("[__t.P.x,__t.P.z,__t.P.yaw]")
        # joystick forward + look right
        await T("touchStart",[(1,(150,280))]);
        for k in range(8):await T("touchMove",[(1,(150,280-8*k))]);await pg.wait_for_timeout(60)
        await T("touchStart",[(1,(150,224)),(2,(560,200))])
        for k in range(6):await T("touchMove",[(1,(150,224)),(2,(560+10*k,200))]);await pg.wait_for_timeout(60)
        await pg.wait_for_timeout(1500)
        await T("touchEnd",[])
        p1=await pg.evaluate("[__t.P.x,__t.P.z,__t.P.yaw]")
        print('moved',round(((p1[0]-p0[0])**2+(p1[1]-p0[1])**2)**.5,2),'yaw change',round(p1[2]-p0[2],3))
        # fire button
        m0=await pg.evaluate("__t.inv[__t.cur].mag")
        box=await pg.evaluate("(()=>{const r=document.getElementById('tFire').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2];})()")
        await T("touchStart",[(3,tuple(box))]);await pg.wait_for_timeout(300);await T("touchEnd",[])
        await pg.wait_for_timeout(300);print('mag',m0,'->',await pg.evaluate("__t.inv[__t.cur].mag"))
        await pg.screenshot(path=str(pathlib.Path(__file__).resolve().parent)+"/t_game.png")
        # giroscopio: inclinare, girarsi, volante, lati 90/270, assi di rotationRate come su iPhone (test/gyro_check.js)
        res=await pg.evaluate("("+(pathlib.Path(__file__).resolve().parent/"gyro_check.js").read_text(encoding="utf-8")+")()")
        for r in res["righe"]:print("  "+r)
        print("gyro","ok" if res["ok"] else "ERRORI")
        if not res["ok"]:errs.append("giroscopio: controlli falliti (righe NO sopra)")
        g=await pg.evaluate("document.getElementById('tGyro').textContent")
        box=await pg.evaluate("(()=>{const r=document.getElementById('tGyro').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2];})()")
        await T("touchStart",[(6,tuple(box))]);await T("touchEnd",[]);await pg.wait_for_timeout(100)
        await T("touchStart",[(6,tuple(box))]);await T("touchEnd",[]);await pg.wait_for_timeout(100)
        g2=await pg.evaluate("document.getElementById('tGyro').textContent")
        print('label',g,'->',g2,'mode',await pg.evaluate("__t.GYRO.mode"))
        await T("touchStart",[(6,tuple(box))]);await T("touchEnd",[]);await pg.wait_for_timeout(100)
        # swap zone & map zone & use hidden
        await pg.evaluate("__t.giveWeapon&&__t.giveWeapon('mastino')");await pg.wait_for_timeout(600)
        c0=await pg.evaluate("__t.cur")
        box=await pg.evaluate("(()=>{const r=document.getElementById('tSwapZ').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2];})()")
        await T("touchStart",[(4,tuple(box))]);await T("touchEnd",[]);await pg.wait_for_timeout(200)
        print('swap',c0,'->',await pg.evaluate("__t.cur"),'use hidden',await pg.evaluate("document.getElementById('tUse').hidden"))
        box=await pg.evaluate("(()=>{const r=document.getElementById('tMapZ').getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2];})()")
        await T("touchStart",[(5,tuple(box))]);await T("touchEnd",[]);await pg.wait_for_timeout(200)
        print('map open',await pg.evaluate("!document.getElementById('mapwrap').hidden"))
        await pg.screenshot(path=str(pathlib.Path(__file__).resolve().parent)+"/t_map.png")
        await T("touchStart",[(5,tuple(box))]);await T("touchEnd",[]);await pg.wait_for_timeout(200)
        print("\n".join(errs[:10]) or "no errors")
        await b.close()
asyncio.run(main())
